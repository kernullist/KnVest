    fn emit_handler_table(&mut self) {
        self.label("handler_table");
        let table_base = self.pos();
        let mut entries: Vec<u32> = vec![0; 256];
        let handlers: [(u8, &str); 16] = [
            (0x00, "h_nop"),
            (0x01, "h_load_imm"),
            (0x04, "h_move"),
            (0x05, "h_add"),
            (0x06, "h_sub"),
            (0x07, "h_mul"),
            (0x09, "h_cmp"),
            (0x0A, "h_jmp"),
            (0x0B, "h_jmpif"),
            (0x0C, "h_call"),
            (0x0D, "h_ret"),
            (0x0E, "h_native_call"),
            (0x0F, "h_push"),
            (0x10, "h_pop"),
            (0x11, "h_load_byte"),
            (0xFF, "h_exit"),
        ];
        let default_off = self.handler_offset("h_nop", table_base);
        for i in 0..256 {
            entries[i] = default_off;
        }
        for (op, label) in handlers {
            entries[op as usize] = self.handler_offset(label, table_base);
        }
        for off in entries {
            self.emit(&off.to_le_bytes());
        }
    }

    fn handler_offset(&self, label: &str, table_base: usize) -> u32 {
        let handler = *self.labels.get(label).unwrap_or(&table_base);
        (handler as i64 - table_base as i64) as u32
    }

